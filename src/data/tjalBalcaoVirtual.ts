/**
 * Busca o Chefe / Diretor(a) de Secretaria competente a partir da Comarca e Vara selecionada,
 * obedecendo estritamente ao Balcão Virtual do TJAL (https://www.tjal.jus.br/balcao-virtual).
 * Em São José da Tapera, mantém o padrão fixado:
 * - Marta Diana Lucindo Tenório (Assessora Judicial)
 */
export function getChefeSecretariaForVara(comarcaName?: string, varaName?: string): {
  nome: string;
  cargo: string;
  telefone?: string;
  email?: string;
} {
  const cNorm = (comarcaName || '').toLowerCase().trim();
  const vNorm = (varaName || '').toLowerCase().trim();

  // Exceção expressa do Tribunal / Usuário: São José da Tapera
  if (cNorm.includes('tapera') || vNorm.includes('tapera')) {
    return {
      nome: 'Marta Diana Lucindo Tenório',
      cargo: 'Assessora Judicial',
      telefone: '3622-1193',
      email: 'saojosedatapera@tjal.jus.br',
    };
  }

  const normalize = (str: string) =>
    str
      .toLowerCase()
      .normalize('NFD')
      .replace(/[̀-ͯ]/g, '')
      .replace(/[^a-z0-9]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();

  const cClean = normalize(cNorm);
  const vClean = normalize(vNorm);

  const isCapital = cClean.includes('maceio') || cClean.includes('capital');

  // 1. Filtrar entradas por comarca se especificada
  const candidates = TJAL_BALCAO_VIRTUAL_DATA.filter((item) => {
    const itemComarca = normalize(item.comarca);
    const itemVara = normalize(item.vara);

    if (isCapital) {
      return itemComarca.includes('maceio') || itemVara.includes('capital');
    }
    if (cClean) {
      return (
        itemComarca.includes(cClean) ||
        cClean.includes(itemComarca) ||
        itemVara.includes(cClean)
      );
    }
    return true;
  });

  // 2. Entre os candidatos da comarca, buscar pela vara
  let match = candidates.find((item) => {
    const itemVara = normalize(item.vara);
    // extrai números de vara (ex: 1ª, 2ª, etc.)
    const itemNum = itemVara.match(/(\d+)/);
    const vNum = vClean.match(/(\d+)/);
    if (itemNum && vNum && itemNum[1] !== vNum[1]) {
      return false;
    }
    return itemVara.includes(vClean) || vClean.includes(itemVara);
  });

  // Se não achou com correspondência total da vara, busca apenas pelo número e ramo (criminal, civel, juizado)
  if (!match && candidates.length > 0) {
    const vNum = vClean.match(/(\d+)/);
    const isCriminal = vClean.includes('crim') || vClean.includes('juri');
    const isCivel = vClean.includes('civ');
    const isJuizado = vClean.includes('juiz');

    match = candidates.find((item) => {
      const itemVara = normalize(item.vara);
      const itemNum = itemVara.match(/(\d+)/);
      if (vNum && itemNum && itemNum[1] === vNum[1]) {
        if (isCriminal && (itemVara.includes('crim') || itemVara.includes('juri'))) return true;
        if (isCivel && itemVara.includes('civ')) return true;
        return true;
      }
      if (!vNum && !itemNum) {
        if (isCriminal && (itemVara.includes('crim') || itemVara.includes('juri'))) return true;
        if (isJuizado && itemVara.includes('juiz')) return true;
        if (isCivel && itemVara.includes('civ')) return true;
      }
      return false;
    });
  }

  // Se ainda não achou, pega o primeiro da comarca com nome preenchido
  if (!match && candidates.length > 0) {
    match = candidates.find((c) => c.secretarioNome);
  }

  // 3. Fallback geral se a comarca não estava no balcão específico
  if (!match) {
    match = TJAL_BALCAO_VIRTUAL_DATA.find((item) => {
      const itemVara = normalize(item.vara);
      return itemVara.includes(vClean) || vClean.includes(itemVara);
    });
  }

  if (match && match.secretarioNome) {
    return {
      nome: match.secretarioNome,
      cargo: 'Diretor(a) de Secretaria',
      telefone: match.telefone,
      email: match.email,
    };
  }

  return {
    nome: match?.secretarioNome || '',
    cargo: 'Diretor(a) de Secretaria',
    telefone: match?.telefone,
    email: match?.email,
  };
}
